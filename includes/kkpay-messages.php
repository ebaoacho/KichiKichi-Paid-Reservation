/**
 * 指定言語のメッセージを返す（fallback: en）
 */
function kkpay_msg( $key, $lang = 'en' ) {
    $msgs = KKPAY_MESSAGES;
    $lang = in_array( $lang, array( 'en', 'ja', 'ko', 'zh-CN', 'zh-TW' ), true ) ? $lang : 'en';
    if ( isset( $msgs[ $key ][ $lang ] ) ) {
        return $msgs[ $key ][ $lang ];
    }
    return $msgs[ $key ]['en'] ?? '';
}
